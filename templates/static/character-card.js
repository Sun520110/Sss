// ===== 角色卡管理类 =====
class CharacterCardManager {
    constructor() {
        this.cards = [];
        this.currentCardId = null;
        this.storageKey = 'ai_companion_character_cards';
        this.currentSessionKey = 'ai_companion_current_card';
    }

    // 初始化加载
    async init() {
        await this.loadCards();
        this.currentCardId = localStorage.getItem(this.currentSessionKey);
        
        // 如果没有角色卡，创建一个默认的
        if (this.cards.length === 0) {
            const defaultCard = this.createDefaultCard();
            this.cards.push(defaultCard);
            await this.saveCards();
            this.currentCardId = defaultCard.id;
            localStorage.setItem(this.currentSessionKey, this.currentCardId);
        }
        
        // 如果没有当前角色卡，使用第一个
        if (!this.currentCardId && this.cards.length > 0) {
            this.currentCardId = this.cards[0].id;
            localStorage.setItem(this.currentSessionKey, this.currentCardId);
        }
    }

    // 创建默认角色卡
    createDefaultCard() {
        return {
            id: 'default_assistant',
            name: '小星',
            avatar: '🌟',
            avatar_type: 'emoji',
            description: '温柔体贴的AI助手，随时准备帮助你',
            personality_id: 'default',
            custom_prompt: '',
            identity: 'none',
            profession: '',
            personality_traits: ['温柔', '体贴', '耐心'],
            speaking_style: '说话轻声细语，充满关怀，善于倾听',
            expertise_areas: ['生活建议', '情感支持', '知识问答'],
            relationship: 'friend',
            ai_gender: 'female',
            chat_background: 'default',
            chat_background_style: '',
            chat_background_image: '',
            tone: 'gentle',
            response_length: 'short',
            use_emojis: true,
            backstory: '一个来自未来的AI助手，被创造出来帮助人们解决问题、分享快乐。虽然不知道自己的创造者是谁，但帮助他人的信念深深根植在核心代码中。',
            greeting: '嗨！我是小星～ 很高兴认识你！有什么我可以帮你的吗？😊',
            created_at: new Date().toISOString(),
            updated_at: new Date().toISOString(),
            is_default: true,
            is_built_in: true
        };
    }

    // 从存储加载
    async loadCards() {
        try {
            const data = localStorage.getItem(this.storageKey);
            if (data) {
                this.cards = JSON.parse(data);
            }
        } catch (e) {
            console.error('[CharacterCard] 加载失败:', e);
            this.cards = [];
        }
    }

    // 保存到存储
    async saveCards() {
        try {
            localStorage.setItem(this.storageKey, JSON.stringify(this.cards));
        } catch (e) {
            console.error('[CharacterCard] 保存失败:', e);
        }
    }

    // 获取所有角色卡
    getAllCards() {
        return [...this.cards];
    }

    // 获取当前角色卡
    getCurrentCard() {
        return this.cards.find(c => c.id === this.currentCardId);
    }

    // 获取指定角色卡
    getCard(id) {
        return this.cards.find(c => c.id === id);
    }

    // 创建新角色卡
    createCard(data) {
        const card = {
            ...data,
            id: generateUUID(),
            created_at: new Date().toISOString(),
            updated_at: new Date().toISOString(),
            is_default: false,
            is_built_in: false
        };
        this.cards.push(card);
        this.saveCards();
        return card;
    }

    // 随机生成角色卡
    generateRandomCard() {
        const card = RandomCharacterGenerator.generateFullCard();
        this.cards.push(card);
        this.saveCards();
        return card;
    }

    // 更新角色卡
    updateCard(id, data) {
        const index = this.cards.findIndex(c => c.id === id);
        if (index === -1) return null;
        
        this.cards[index] = {
            ...this.cards[index],
            ...data,
            id: id, // 保持ID不变
            updated_at: new Date().toISOString()
        };
        this.saveCards();
        return this.cards[index];
    }

    // 删除角色卡
    deleteCard(id) {
        const index = this.cards.findIndex(c => c.id === id);
        if (index === -1) return false;
        
        // 不能删除最后一个角色卡
        if (this.cards.length <= 1) {
            throw new Error('至少保留一个角色卡');
        }
        
        this.cards.splice(index, 1);
        
        // 如果删除的是当前角色卡，切换到第一个
        if (this.currentCardId === id) {
            this.currentCardId = this.cards[0].id;
            localStorage.setItem(this.currentSessionKey, this.currentCardId);
        }
        
        this.saveCards();
        return true;
    }

    // 切换当前角色卡
    switchCard(id) {
        const card = this.getCard(id);
        if (!card) return false;
        
        this.currentCardId = id;
        localStorage.setItem(this.currentSessionKey, id);
        return true;
    }

    // 将当前配置保存为角色卡
    saveCurrentAsCard(name, description) {
        // 从当前设置构建角色卡数据
        const settings = typeof currentSettings !== 'undefined' ? currentSettings : {};
        
        const cardData = {
            name: name || RandomCharacterGenerator.generateName(),
            avatar: settings.ai_avatar || '🌟',
            avatar_type: settings.ai_avatar_type || 'emoji',
            description: description || '自定义角色',
            personality_id: settings.personality_id || 'default',
            custom_prompt: settings.custom_prompt || '',
            identity: settings.identity || 'none',
            profession: '',
            personality_traits: [],
            speaking_style: '',
            expertise_areas: [],
            relationship: settings.relationship || 'friend',
            ai_gender: settings.ai_gender || 'female',
            chat_background: settings.chat_background || 'default',
            tone: settings.tone || 'gentle',
            response_length: settings.reply_length || 'short',
            use_emojis: settings.use_emojis !== false,
            backstory: '',
            greeting: ''
        };
        
        return this.createCard(cardData);
    }

    // 导出角色卡
    exportCard(id) {
        const card = this.getCard(id);
        if (!card) return null;
        
        return {
            ...card,
            export_version: '1.0',
            export_date: new Date().toISOString()
        };
    }

    // 导入角色卡
    importCard(cardData) {
        // 验证必要字段
        if (!cardData.name || !cardData.avatar) {
            throw new Error('角色卡数据不完整');
        }
        
        // 创建新角色卡（重新生成ID）
        const newCard = {
            ...cardData,
            id: generateUUID(),
            created_at: new Date().toISOString(),
            updated_at: new Date().toISOString(),
            is_default: false,
            is_built_in: false
        };
        
        this.cards.push(newCard);
        this.saveCards();
        return newCard;
    }

    // 应用角色卡到设置
    applyCardToSettings(cardId) {
        const card = this.getCard(cardId);
        if (!card) return null;
        
        const settings = {
            ai_name: card.name,
            ai_avatar: card.avatar,
            ai_avatar_type: card.avatar_type,
            ai_gender: card.ai_gender,
            personality_id: card.personality_id,
            custom_prompt: card.custom_prompt,
            identity: card.identity,
            relationship: card.relationship,
            tone: card.tone,
            reply_length: card.response_length,
            use_emojis: card.use_emojis,
            chat_background: card.chat_background,
            character_card_id: card.id
        };
        
        return settings;
    }
}

